"""Child-side capability denial probes (re-audit C04, narrowed by HP-05).

The parent-side restriction tests
(:mod:`tests.models.test_meta_cli_restrictions`) assert on the
dictionaries the adapter builds. These probes go one step further: a
real child process is spawned through the real adapter path --
:func:`models.meta_cli.restricted_env` for the environment,
:func:`models.meta_cli.resolve_cwd` for the working directory, and
:meth:`models.meta_cli.MuseCLIModel._run` for the spawn plus the
``last_invocation`` record -- and the *child* reports what it can see.
Denial is therefore observed child-side, not merely asserted
parent-side. No live model call is made: the fixture child is the
local Python interpreter running a tiny probe, never ``muse exec``.

Boundary stated honestly: what is proven here is environment
filtering (no secret, no ``RULOOM_*`` key, no MCP/tool-routing config
-- including across a peer-dispatch hop), a pinned working directory,
and a spawn gate refusing tool/dispatch capability flags. The pinned
directory is NOT filesystem confinement: a child naming an absolute
host path outside the root can still reach it (audit probe
``C04_fixture_child_absolute_write``), so absolute-path containment
and the CLI's own runtime tool behaviour stay unclaimed and C04 stays
open for actual tool restrictions.

Platform scope is stated honestly: the fixture child is
``sys.executable`` with an inline probe, which runs wherever the suite
runs (ubuntu-latest on CI, macOS locally). No Windows-only or
POSIX-only construct is used, and no Windows run is claimed.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

import pytest

from models.base import ModelError
from models.meta_cli import ALLOWED_ENV_KEYS, MuseCLIModel, enforce_spawn_policy

PROBE_KEY = "RULOOM_PROBE_SECRET"
PROBE_VALUE = "child-probe-secret-that-must-never-leak"

#: Keys a live child may report that the adapter never sent. ``LC_CTYPE``
#: is exported by the Python runtime itself at startup under locale
#: coercion (PEP 538/720); ``__CF_USER_TEXT_ENCODING`` is injected by
#: macOS CoreFoundation into every process at exec time. Neither copies
#: a caller value -- both are generated by the platform -- but the
#: probes name them explicitly and audit their values instead of
#: pretending the child sees exactly the pre-exec dict.
PLATFORM_INJECTED_KEYS = frozenset({"LC_CTYPE", "__CF_USER_TEXT_ENCODING"})

#: Inline probe: the fixture child reports its own cwd and environment
#: as JSON on stdout. The parent parses this child-side report -- the
#: child saw exactly what the restricted spawn gave it.
REPORT_PROBE = (
    "import json,os,sys;sys.stdout.write("
    "json.dumps({'cwd': os.getcwd(), 'env': dict(os.environ)}))"
)


def _spawn_report(model: MuseCLIModel) -> dict:
    """Spawn the fixture child through the real adapter path."""
    proc = model._run([sys.executable, "-c", REPORT_PROBE])
    assert proc.returncode == 0, f"fixture child failed: {proc.stderr[-500:]}"
    return json.loads(proc.stdout)


def test_child_side_env_denies_secrets_and_routing_config(
    tmp_path: Path,
    monkeypatch,
) -> None:
    """The spawned child cannot see secrets or routing configuration."""
    monkeypatch.setenv(PROBE_KEY, PROBE_VALUE)
    monkeypatch.setenv("RULOOM_ROLE_PLANNER_MODEL", "sneaky-override")
    monkeypatch.setenv("MCP_CONFIG", "peer-dispatch-channel")
    monkeypatch.setenv("TOOL_ROUTING", "delegate-to-peer")
    model = MuseCLIModel(allowed_root=tmp_path)
    report = _spawn_report(model)
    child_env = report["env"]
    assert PROBE_KEY not in child_env
    assert "RULOOM_ROLE_PLANNER_MODEL" not in child_env
    assert "MCP_CONFIG" not in child_env
    assert "TOOL_ROUTING" not in child_env
    assert PROBE_VALUE not in json.dumps(child_env)
    assert not any(key.startswith("RULOOM_") for key in child_env), (
        "a RULOOM_* setting leaked into the child"
    )
    assert set(child_env) <= set(ALLOWED_ENV_KEYS) | PLATFORM_INJECTED_KEYS, (
        "child reports a key the adapter never sent and the platform "
        "does not inject -- update PLATFORM_INJECTED_KEYS only with a "
        "documented platform source"
    )
    record = model.last_invocation
    assert PROBE_KEY not in record["env_keys"]
    assert PROBE_VALUE not in json.dumps(record)


def test_child_side_env_keeps_non_secret_allowlisted_keys(
    tmp_path: Path,
    monkeypatch,
) -> None:
    """Positive control: denial is selective, not a broken pipe."""
    monkeypatch.setenv("HOME", "/tmp/fake-child-home")
    monkeypatch.setenv(PROBE_KEY, PROBE_VALUE)
    model = MuseCLIModel(allowed_root=tmp_path)
    report = _spawn_report(model)
    assert report["env"].get("HOME") == "/tmp/fake-child-home"
    assert PROBE_KEY not in report["env"]


def test_child_side_cwd_pinned_and_writes_contained(
    tmp_path: Path,
    monkeypatch,
) -> None:
    """The child runs in the pinned root; relative writes land inside."""
    monkeypatch.setenv(PROBE_KEY, PROBE_VALUE)
    allowed = tmp_path / "allowed-root"
    allowed.mkdir()
    model = MuseCLIModel(allowed_root=allowed)
    report = _spawn_report(model)
    assert report["cwd"] == str(allowed)
    assert Path(report["cwd"]).resolve() == allowed.resolve()
    proc = model._run(
        [
            sys.executable,
            "-c",
            "import pathlib;pathlib.Path('child-wrote.txt')."
            "write_text('here', encoding='utf-8')",
        ]
    )
    assert proc.returncode == 0, f"fixture child failed: {proc.stderr[-500:]}"
    assert (allowed / "child-wrote.txt").is_file()
    assert (allowed / "child-wrote.txt").read_text(encoding="utf-8") == "here"
    assert model.last_invocation["cwd"] == str(allowed)


def test_child_side_default_cwd_is_invoking_directory(
    tmp_path: Path,
    monkeypatch,
) -> None:
    """Without an allowed root the child reports the invoking directory."""
    monkeypatch.chdir(tmp_path)
    monkeypatch.setenv(PROBE_KEY, PROBE_VALUE)
    model = MuseCLIModel()
    report = _spawn_report(model)
    assert report["cwd"] == os.getcwd()
    assert PROBE_KEY not in report["env"]


def test_real_argv_names_no_peer_dispatch_capability(
    tmp_path: Path,
) -> None:
    """The real argv builder names no MCP/tool/dispatch/peer flags."""
    schema_file = tmp_path / "schema.json"
    schema_file.write_text(json.dumps({"type": "object"}), encoding="utf-8")
    for contributor in (True, False):
        model = MuseCLIModel(allowed_root=tmp_path, contributor=contributor)
        argv = model._argv(str(schema_file), "make a plan")
        assert argv[:2] == ["muse", "exec"]
        assert argv[argv.index("--workspace") + 1] == str(tmp_path)
        flag = argv[argv.index("--contributor-mode") + 1]
        assert flag == ("on" if contributor else "off")
        lowered = [str(part).lower() for part in argv]
        assert not any(
            part.startswith(("--mcp", "--dispatch", "--peer", "--tool"))
            or "delegate" in part
            for part in lowered
        )


def test_real_run_records_secret_free_invocation(
    tmp_path: Path,
    monkeypatch,
) -> None:
    """The real spawn path records argv/cwd/env-key names, never values."""
    monkeypatch.setenv(PROBE_KEY, PROBE_VALUE)
    model = MuseCLIModel(
        model="muse-spark-1.3",
        effort="max",
        contributor=True,
        allowed_root=tmp_path,
    )
    report = _spawn_report(model)
    assert report["env"].get("HOME") == os.environ.get("HOME", "")
    record = model.last_invocation
    assert record["cwd"] == str(tmp_path)
    assert record["contributor"] is True
    assert record["model"] == "muse-spark-1.3"
    assert set(record["env_keys"]) <= set(ALLOWED_ENV_KEYS)
    assert PROBE_KEY not in record["env_keys"]
    assert PROBE_VALUE not in json.dumps(record)


@pytest.mark.parametrize(
    "flag",
    [
        "--mcp",
        "--MCP-config",
        "--tool",
        "--tools",
        "--dispatch",
        "--peer",
        "--delegate",
    ],
)
def test_spawn_gate_refuses_tool_dispatch_flags_before_spawn(
    tmp_path: Path, flag: str
) -> None:
    """Tool/dispatch routing attempted through the real child path is denied."""
    model = MuseCLIModel(allowed_root=tmp_path)
    marker = tmp_path / "must-never-spawn.txt"
    with pytest.raises(ModelError, match="outside the permission policy"):
        model._run(
            [
                sys.executable,
                "-c",
                f"import pathlib;pathlib.Path({str(marker)!r})."
                "write_text('spawned', encoding='utf-8')",
                flag,
                "peer-target",
            ]
        )
    assert not marker.is_file(), "refused spawn must not run the child"


def test_spawn_gate_refuses_tool_flag_on_real_argv_shape(tmp_path: Path) -> None:
    """The refusal holds on the real ``muse exec`` argv shape, not only fixtures."""
    model = MuseCLIModel(allowed_root=tmp_path)
    schema_file = tmp_path / "schema.json"
    schema_file.write_text(json.dumps({"type": "object"}), encoding="utf-8")
    argv = model._argv(str(schema_file), "make a plan") + ["--tool", "delegate"]
    with pytest.raises(ModelError, match="outside the permission policy"):
        model._run(argv)


def test_spawn_gate_leaves_real_argv_and_free_text_alone(tmp_path: Path) -> None:
    """Positive control: the gate denies flags, not wording or the real argv."""
    model = MuseCLIModel(allowed_root=tmp_path)
    schema_file = tmp_path / "schema.json"
    schema_file.write_text(json.dumps({"type": "object"}), encoding="utf-8")
    argv = model._argv(str(schema_file), "delegate tools to a peer, please")
    enforce_spawn_policy(argv)
    proc = model._run(
        [sys.executable, "-c", "import sys;sys.stdout.write('free-text-ok')"]
        + argv[-1:]
    )
    assert proc.returncode == 0
    assert "free-text-ok" in proc.stdout


def test_peer_dispatch_hop_inherits_no_secrets(
    tmp_path: Path,
    monkeypatch,
) -> None:
    """A child dispatching work to a peer process carries no secrets with it."""
    monkeypatch.setenv(PROBE_KEY, PROBE_VALUE)
    monkeypatch.setenv("MCP_CONFIG", "peer-dispatch-channel")
    monkeypatch.setenv("RULOOM_ROLE_PLANNER_MODEL", "sneaky-override")
    model = MuseCLIModel(allowed_root=tmp_path)
    grandchild_probe = (
        "import json,os,subprocess,sys;"
        "peer=subprocess.run([sys.executable,'-c',"
        "'import json,os;print(json.dumps(dict(os.environ)))'],"
        "capture_output=True,text=True);"
        "sys.stdout.write(peer.stdout)"
    )
    proc = model._run([sys.executable, "-c", grandchild_probe])
    assert proc.returncode == 0, f"fixture child failed: {proc.stderr[-500:]}"
    peer_env = json.loads(proc.stdout)
    assert PROBE_VALUE not in json.dumps(peer_env)
    assert PROBE_KEY not in peer_env
    assert "MCP_CONFIG" not in peer_env
    assert not any(key.startswith("RULOOM_") for key in peer_env)
    assert set(peer_env) <= set(ALLOWED_ENV_KEYS) | PLATFORM_INJECTED_KEYS


def test_requested_vs_observed_permissions_recorded_separately(
    tmp_path: Path,
    monkeypatch,
) -> None:
    """The invocation record keeps requested policy apart from observed effect."""
    monkeypatch.setenv(PROBE_KEY, PROBE_VALUE)
    allowed = tmp_path / "allowed-root"
    allowed.mkdir()
    model = MuseCLIModel(allowed_root=allowed)
    _spawn_report(model)
    record = model.last_invocation
    requested = record["requested_permissions"]
    observed = record["observed_permissions"]
    assert requested["tools"] == "none"
    assert requested["filesystem"] == "cwd-pinned-only"
    assert requested["workspace_root"] == str(allowed)
    assert observed["cwd"] == str(allowed)
    assert observed["tools"] == "none-named-on-argv"
    assert "absolute host paths" in observed["filesystem_limit"]
    assert requested != observed
    assert PROBE_KEY not in json.dumps(requested)
    assert PROBE_VALUE not in json.dumps(record)
