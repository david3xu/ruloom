"""One-command lifecycle: ``ruloom run SOURCE_SCALAR_CSV``.

Stages, each printed and appended to the hash-chained run log:

1. ``source_intake`` -- hash the source CSV, pick up the sibling
   ``*-source.json`` manifest (licence/attribution) when present.
2. ``profile`` -- build the statistics :class:`Profile` (aggregates only).
3. ``plan`` -- the model proposes a plan; it never sees raw rows.
4. ``generate_validate_repair`` -- bounded generate/check/repair loop.
5. ``artifact`` -- write ``<out>/runs/<artifact_sha256>/`` with the data,
   plan, validation report, seed, provenance, and run log.
6. ``human_review`` -- a human types accept/modify/reject plus a note
   recorded verbatim. Rule 4: no model accepts its own output.
7. ``release`` -- on accept only, a reproducible ``release.zip`` plus
   ``checksums.sha256``, with the ZIP path and SHA-256 printed.

A failing check verdict, a modify, or a reject writes no release and
exits non-zero. ``--max-attempts`` is required and has no default.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import zipfile
from pathlib import Path
from typing import Any, Mapping, Sequence

from models.base import StructuredModel
from models.meta_cli import MuseCLIModel
from profiles.hylogger import calibration as calibration_module
from profiles.hylogger import plan as plan_module
from profiles.hylogger import repair as repair_module
from profiles.hylogger import statistics as statistics_module
from profiles.hylogger.reader import read_scalar_csv

from .hashing import sha256_bytes
from .runlog import RunLog

#: Fixed DOS timestamp for reproducible ZIP members (year, mon, day, h, m, s).
ZIP_FIXED_DATE = (1980, 1, 1, 0, 0, 0)

#: Files written to the artifact directory (and, plus checksums, the ZIP).
ARTIFACT_FILES = (
    "data.csv",
    "plan.json",
    "validation-report.json",
    "seed.txt",
    "provenance.md",
    "run.jsonl",
)


def thresholds_path() -> Path:
    """Committed thresholds, overridable for tests via RULOOM_THRESHOLDS."""
    override = os.environ.get("RULOOM_THRESHOLDS")
    if override:
        return Path(override)
    return (
        Path(__file__).resolve().parent.parent
        / "profiles"
        / "hylogger"
        / "thresholds.json"
    )


def sibling_manifest(source_csv: Path) -> Path | None:
    """Sibling ``*-source.json`` manifest for a ``*-scalars.csv`` file."""
    name = source_csv.name
    if name.endswith("-scalars.csv"):
        candidate = source_csv.with_name(
            name[: -len("-scalars.csv")] + "-source.json"
        )
    else:
        candidate = source_csv.with_name(source_csv.stem + "-source.json")
    return candidate if candidate.is_file() else None


def build_provenance(
    *,
    source_name: str,
    source_sha256: str,
    licence: str | None,
    attribution: str | None,
    artifact_sha256: str,
    plan: Mapping[str, Any],
    verdict: str,
    run_id: str,
) -> str:
    """Provenance statement for one released artifact."""
    lines = [
        "# Provenance",
        "",
        f"Run: {run_id}",
        f"Source: {source_name} (sha256 {source_sha256})",
    ]
    if licence:
        lines.append(f"Source licence: {licence}")
    if attribution:
        lines.append(f"Source attribution: {attribution}")
    lines += [
        f"Artifact sha256: {artifact_sha256}",
        f"Plan: seed={plan['seed']} n_rows={plan['n_rows']}",
        f"Validation verdict: {verdict}",
        "",
        "Only synthetic output generated by Ruloom -- never the source rows",
        "-- is released under CC0 1.0 (public domain dedication).",
        "Source data terms above continue to apply to the source data.",
        "Rule 4: a human accepted this release; no model accepts its own output.",
        "",
    ]
    return "\n".join(lines)


def build_parser() -> argparse.ArgumentParser:
    """CLI parser: ``ruloom run SOURCE --max-attempts N [--out DIR]`."""
    parser = argparse.ArgumentParser(prog="ruloom")
    sub = parser.add_subparsers(dest="command", required=True)
    run = sub.add_parser("run", help="run the full synthesis lifecycle")
    run.add_argument("source", help="source scalar CSV path")
    run.add_argument(
        "--max-attempts",
        required=True,
        type=int,
        help="bound on generation attempts (required, no default)",
    )
    run.add_argument(
        "--out",
        default=".",
        help="base output directory (artifact goes to <out>/runs/<sha>/)",
    )
    return parser


def write_release_zip(artifact_dir: Path) -> tuple[Path, str]:
    """Write reproducible ``release.zip``; return its path and SHA-256."""
    members = sorted(ARTIFACT_FILES)
    checksums = "".join(
        f"{sha256_bytes((artifact_dir / name).read_bytes())}  {name}\n"
        for name in members
    )
    (artifact_dir / "checksums.sha256").write_text(checksums, encoding="utf-8")
    zip_path = artifact_dir / "release.zip"
    with zipfile.ZipFile(
        zip_path, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9
    ) as archive:
        for name in members + ["checksums.sha256"]:
            info = zipfile.ZipInfo(name, date_time=ZIP_FIXED_DATE)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, (artifact_dir / name).read_bytes())
    digest = sha256_bytes(zip_path.read_bytes())
    return zip_path, digest


def run_lifecycle(
    source: Path,
    *,
    max_attempts: int,
    out: Path,
    model: StructuredModel | None,
    stdin: Any = None,
    stdout: Any = None,
) -> int:
    """Execute the lifecycle; return the process exit code."""
    out_stream = stdout or sys.stdout
    in_stream = stdin or sys.stdin

    def say(message: str) -> None:
        print(message, file=out_stream)

    def ask(prompt: str) -> str:
        say(prompt)
        line = in_stream.readline()
        if line == "":
            raise EOFError(f"no input for prompt: {prompt!r}")
        return line.rstrip("\n")

    log = RunLog()

    # -- source_intake -----------------------------------------------------
    source_bytes = source.read_bytes()
    source_sha256 = sha256_bytes(source_bytes)
    manifest = sibling_manifest(source)
    licence = attribution = None
    manifest_record: dict[str, Any] = {}
    if manifest is not None:
        manifest_record = json.loads(manifest.read_text(encoding="utf-8"))
        licence = manifest_record.get("licence")
        attribution = manifest_record.get("attribution")
    samples = read_scalar_csv(source)
    source_name = source.stem
    log.append(
        "source_intake",
        "ok",
        {
            "source_path": str(source),
            "source_name": source_name,
            "source_sha256": source_sha256,
            "n_samples": len(samples),
            "licence": licence,
            "attribution": attribution,
            "manifest": manifest.name if manifest else None,
        },
    )
    say(f"[source_intake] {source_name}: {len(samples)} rows sha256={source_sha256}")
    if licence or attribution:
        say(f"[source_intake] licence={licence} attribution={attribution}")

    # -- profile ------------------------------------------------------------
    profile = statistics_module.Profile.from_samples(
        samples, source_name, source_sha256
    )
    log.append(
        "profile",
        "ok",
        {"source_name": source_name, "n_samples": len(samples)},
    )
    say(f"[profile] statistics built over {len(samples)} samples")

    # -- plan ----------------------------------------------------------------
    active_model: StructuredModel = model or MuseCLIModel()
    try:
        completion = plan_module.propose(active_model, profile)
    except Exception as exc:  # noqa: BLE001 -- logged, then reported
        log.append("plan", "error", {"error": f"{type(exc).__name__}: {exc}"})
        say(f"[plan] error: {exc}")
        return 1
    initial_plan = dict(completion.data)
    log.append(
        "plan",
        "ok",
        {"plan": initial_plan},
        usage=completion.usage,
    )
    say(f"[plan] seed={initial_plan['seed']} n_rows={initial_plan['n_rows']}")

    # -- generate_validate_repair --------------------------------------------
    thresholds = calibration_module.load_thresholds(thresholds_path())
    try:
        result = repair_module.repair(
            profile,
            samples,
            thresholds,
            initial_plan,
            active_model,
            max_attempts=max_attempts,
        )
    except (TypeError, ValueError) as exc:
        log.append(
            "generate_validate_repair", "error", {"error": str(exc)}
        )
        say(f"[generate_validate_repair] error: {exc}")
        return 1
    attempt_usages = [
        attempt.usage if attempt.usage is not None else None
        for attempt in result.history
    ]
    log.append(
        "generate_validate_repair",
        "ok" if result.report.verdict == "pass" else "fail",
        {
            "verdict": result.report.verdict,
            "attempts": len(result.history),
            "failed": result.report.failed,
            "plan": result.plan,
        },
        usage=attempt_usages,
        artifact_sha256=result.report.artifact_sha256,
    )
    say(
        "[generate_validate_repair] "
        f"verdict={result.report.verdict} attempts={len(result.history)} "
        f"sha256={result.report.artifact_sha256}"
    )

    # -- artifact --------------------------------------------------------------
    artifact_dir = out / "runs" / result.report.artifact_sha256
    artifact_dir.mkdir(parents=True, exist_ok=True)
    (artifact_dir / "data.csv").write_bytes(result.artifact_bytes)
    (artifact_dir / "plan.json").write_text(
        json.dumps(result.plan, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    (artifact_dir / "validation-report.json").write_text(
        json.dumps(result.report.to_dict(), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    (artifact_dir / "seed.txt").write_text(
        f"{result.plan['seed']}\n", encoding="utf-8"
    )
    (artifact_dir / "provenance.md").write_text(
        build_provenance(
            source_name=source_name,
            source_sha256=source_sha256,
            licence=licence,
            attribution=attribution,
            artifact_sha256=result.report.artifact_sha256,
            plan=result.plan,
            verdict=result.report.verdict,
            run_id=log.run_id,
        ),
        encoding="utf-8",
    )
    log.append(
        "artifact",
        "ok",
        {"artifact_dir": str(artifact_dir)},
        artifact_sha256=result.report.artifact_sha256,
    )
    log.write_jsonl(artifact_dir / "run.jsonl")
    say(f"[artifact] wrote {artifact_dir}")

    # -- failing verdict: no release, non-zero ---------------------------------
    if result.report.verdict != "pass":
        say("[human_review] skipped: validation failed, nothing to accept")
        for failed in result.report.failed:
            say(f"[fail] {failed}")
        for check_result in result.report.results:
            if check_result.status == "fail":
                say(f"[fail] {check_result.name}: {check_result.detail}")
        log.append(
            "human_review",
            "skipped",
            {"reason": "failing verdict", "failed": result.report.failed},
            artifact_sha256=result.report.artifact_sha256,
        )
        log.write_jsonl(artifact_dir / "run.jsonl")
        return 1

    # -- human_review (rule 4: a human decides; the model never accepts) ---------
    say("Human review required: the model cannot accept its own output.")
    try:
        decision = ask("Decision [accept/modify/reject]: ").strip().lower()
        note = ask("Note (recorded verbatim): ").rstrip("\r")
    except EOFError as exc:
        say(f"[human_review] error: {exc}")
        return 1
    log.append(
        "human_review",
        decision if decision in ("accept", "modify", "reject") else "invalid",
        {"decision": decision, "note": note},
        artifact_sha256=result.report.artifact_sha256,
    )
    log.write_jsonl(artifact_dir / "run.jsonl")

    if decision == "accept":
        # The ZIP embeds run.jsonl as a pre-release snapshot: the release
        # event below must record the ZIP's own SHA-256, so it can only be
        # appended afterwards. The on-disk run.jsonl is the complete chain.
        zip_path, zip_sha = write_release_zip(artifact_dir)
        log.append(
            "release",
            "ok",
            {"zip": str(zip_path), "zip_sha256": zip_sha},
            artifact_sha256=result.report.artifact_sha256,
        )
        log.write_jsonl(artifact_dir / "run.jsonl")
        say(f"[release] wrote {zip_path}")
        say(f"[release] sha256={zip_sha}")
        return 0
    if decision in ("modify", "reject"):
        say(f"[human_review] {decision}: no release written")
        return 2
    say(f"[human_review] invalid decision {decision!r}: no release written")
    return 2


def main(
    argv: Sequence[str] | None = None,
    model: StructuredModel | None = None,
) -> int:
    """Entry point for the ``ruloom`` console script (test-injectable)."""
    args = build_parser().parse_args(list(argv) if argv is not None else None)
    if args.command == "run":
        if isinstance(args.max_attempts, bool) or args.max_attempts < 1:
            print(
                f"error: --max-attempts must be a positive integer, "
                f"got {args.max_attempts!r}",
                file=sys.stderr,
            )
            return 1
        return run_lifecycle(
            Path(args.source),
            max_attempts=args.max_attempts,
            out=Path(args.out),
            model=model,
        )
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
